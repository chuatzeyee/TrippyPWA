// The generated land outlines (blueprint 1.3, section 10 row 27, 9.4 item 11): three non-empty paths
// within budget, produced by scripts/build-world-land.mjs and by nothing else, and the regional file
// reachable only through a dynamic import. Owner: F7.
import { describe, it, expect } from 'vitest';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LAND_WORLD } from './world-land.js';
import { LAND_EUROPE, LAND_APAC } from './world-land-regions.js';
import { OUTLINES, DATA_DIR, buildWorldLand, landPath } from '../../../scripts/build-world-land.mjs';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const read = (file) => readFileSync(ROOT + file, 'utf8');
// Other tasks create and move files while this runs: a file that has just gone reads as empty in a scan.
const scan = (file) => { try { return read(file); } catch { return ''; } };
const bytes = (text) => Buffer.byteLength(text);
// Rings only: "M x y l dx dy ... z", whole numbers, a minus sign standing in for the space.
const RINGS = /^(M-?\d+[ -]\d+l(?:[ -]?\d+)+z)+$/;

/** The corners of everything a path draws, in world units. */
function extent(path) {
  let [minX, minY, maxX, maxY] = [Infinity, Infinity, -Infinity, -Infinity];
  for (const ring of path.split('z').filter(Boolean)) {
    const numbers = ring.match(/-?\d+/g).map(Number);
    let [x, y] = [0, 0];
    for (let i = 0; i < numbers.length; i += 2) {
      [x, y] = i === 0 ? [numbers[0], numbers[1]] : [x + numbers[i], y + numbers[i + 1]];
      [minX, minY, maxX, maxY] = [Math.min(minX, x), Math.min(minY, y), Math.max(maxX, x), Math.max(maxY, y)];
    }
  }
  return { minX, minY, maxX, maxY };
}

describe('the generated outlines', () => {
  it.each([['LAND_WORLD', LAND_WORLD], ['LAND_EUROPE', LAND_EUROPE], ['LAND_APAC', LAND_APAC]])('%s is a non-empty path of closed rings', (_name, path) => {
    expect(path.length).toBeGreaterThan(2000);
    expect(RINGS.test(path)).toBe(true);
  });

  it('stays within budget: the world at most 25 KB, the two regions together at most 50 KB', () => {
    expect(bytes(read('js/views/shared/world-land.js'))).toBeLessThanOrEqual(25_000);
    expect(bytes(read('js/views/shared/world-land-regions.js'))).toBeLessThanOrEqual(50_000);
    expect(OUTLINES.map((outline) => outline.maxBytes)).toEqual([25_000, 50_000]);
  });

  it('draws each outline inside its box, in the world units of js/lib/geo.js', () => {
    // x = lon * 10. The world reaches past both ends of the map (rings that cross the 180th meridian are drawn twice).
    const world = extent(LAND_WORLD);
    expect(world.minX).toBeLessThan(-1700);
    expect(world.maxX).toBeGreaterThan(1700);
    expect(world.minX).toBeGreaterThanOrEqual(-1920);
    expect(world.maxX).toBeLessThanOrEqual(1920);
    const europe = extent(LAND_EUROPE);
    expect(europe.minX).toBeGreaterThanOrEqual(-480);
    expect(europe.maxX).toBeLessThanOrEqual(600);
    const apac = extent(LAND_APAC);
    expect(apac.minX).toBeGreaterThanOrEqual(600);
    expect(apac.maxX).toBeLessThanOrEqual(1800);
    // North is negative y: Europe sits above the equator, Asia-Pacific spans it.
    expect(europe.maxY).toBeLessThan(0);
    expect(apac.minY).toBeLessThan(0);
    expect(apac.maxY).toBeGreaterThan(0);
  });

  it('keeps the preview boxes and tolerances', () => {
    const [world, regions] = OUTLINES;
    expect(world.source).toBe('land-110m.json');
    expect(world.paths).toEqual([{ name: 'LAND_WORLD', box: [-192, -58, 192, 84], tol: 5 }]);
    expect(regions.source).toBe('land-50m.json');
    expect(regions.paths).toEqual([
      { name: 'LAND_EUROPE', box: [-48, 36, 60, 78], tol: 1.2 },
      { name: 'LAND_APAC', box: [60, -56, 180, 62], tol: 2 },
    ]);
  });

  it('says in each file that it is generated', () => {
    for (const { file } of OUTLINES) expect(read(file)).toMatch(/^\/\/ Generated by scripts\/build-world-land\.mjs from previews\/c-atlas\/data\/land-\d+m\.json/);
  });
});

describe('landPath', () => {
  // One square island, 10 degrees wide, as the smallest possible topology.
  const square = { transform: { scale: [1, 1], translate: [0, 0] }, arcs: [[[0, 0], [10, 0], [0, 10], [-10, 0], [0, -10]]], objects: { land: { type: 'Polygon', arcs: [[0]] } } };

  it('turns a ring into one closed piece of relative steps', () => {
    expect(landPath(square, { box: [-180, -80, 180, 80], tol: 1 })).toBe('M0 0l100 0 0-100-100 0 0 100z');
  });
  it('clips to the box', () => {
    expect(extent(landPath(square, { box: [-180, -80, 5, 80], tol: 1 })).maxX).toBe(50);
  });
  it('drops a ring that is smaller than the tolerance, and one outside the box', () => {
    expect(landPath(square, { box: [-180, -80, 180, 80], tol: 200 })).toBe('');
    expect(landPath(square, { box: [40, -80, 180, 80], tol: 1 })).toBe('');
  });
});

// previews/ is not in a checkout (it is untracked), so this half skips itself there.
describe.skipIf(!existsSync(DATA_DIR))('the script is the only source of the two files', () => {
  it('generates exactly what is on disk', () => {
    for (const { file, text, maxBytes } of buildWorldLand()) {
      expect(read(file), `${file} differs from the script output: run node scripts/build-world-land.mjs`).toBe(text);
      expect(bytes(text)).toBeLessThanOrEqual(maxBytes);
    }
  });
});

describe('the regional outlines are loaded on demand only', () => {
  const sources = (dir) => readdirSync(ROOT + dir, { withFileTypes: true }).flatMap((entry) => (
    entry.isDirectory() ? sources(`${dir}/${entry.name}`) : /\.m?js$/.test(entry.name) && !/\.test\.m?js$/.test(entry.name) ? [`${dir}/${entry.name}`] : []));
  // `import(` is the dynamic form, also when it starts a line (the Atlas page's `import(...).then(...)`).
  const STATIC = /(?:^|[\n;])\s*(?:import|export)\b(?!\s*\()[^;'"]*['"][^'"]*world-land-regions\.js['"]/;

  it('no source file imports world-land-regions.js statically', () => {
    const files = sources('js');
    expect(files.length).toBeGreaterThan(50);
    expect(files.filter((file) => STATIC.test(scan(file)))).toEqual([]);
  });
  it('the check can fail', () => {
    expect(STATIC.test("import { LAND_APAC } from '../shared/world-land-regions.js';")).toBe(true);
    expect(STATIC.test("export * from './world-land-regions.js';")).toBe(true);
    expect(STATIC.test("const regions = () => import('../shared/world-land-regions.js');")).toBe(false);
    expect(STATIC.test("if (switcher) {\n    import('../shared/world-land-regions.js').then(use);\n}")).toBe(false);
    expect(STATIC.test("const a = 1;\nimport {\n  LAND_EUROPE,\n} from './world-land-regions.js';")).toBe(true);
  });
});
